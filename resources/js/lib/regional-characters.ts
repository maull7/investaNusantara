/**
 * Mascot per province for the region map: a small chibi wearing the province's
 * traditional attire, who waves hello and now and then shows off something
 * the region is known for. Keyed by Kemendagri province code.
 *
 * Kept deliberately simple (a few colours + a headwear and prop shape) so the
 * characters stay readable at ~80px and are easy to adjust here.
 */

export type Headwear =
    | "peci" // black cap (Betawi, Melayu)
    | "songkok" // gold-woven cap (Bugis, Mandar)
    | "blangkon" // Solo-style
    | "blangkon-mondol" // Yogyakarta, with the knot at the back
    | "udeng" // Bali
    | "iket" // Sunda / Banten head cloth
    | "tanjak" // Melayu folded head cloth
    | "meukeutop" // Aceh striped tall cap
    | "suntiang" // Minangkabau gold fan crown
    | "siger" // Lampung gold crown
    | "crown" // generic gold bridal crown (Palembang, Banjar, Gorontalo…)
    | "feathers-dayak" // hornbill feathers
    | "feathers-papua" // colourful bird-of-paradise feathers
    | "tilangga" // Rote palm hat with a horn (NTT)
    | "flowers" // Balinese flower crown
    | "headband" // tied cloth band (Batak, Sasak, Madura, Minahasa…)
    | "bun"; // hair bun with gold pins

export type Trim =
    | "none"
    | "collar" // gold neckline
    | "sash" // cloth over one shoulder
    | "vest" // open vest over the shirt
    | "stripes" // horizontal stripes (Madura)
    | "vstripes" // vertical lurik stripes (surjan)
    | "checks" // checked (cele, sarong)
    | "beads"; // beaded necklace/vest (Dayak, Papua)

export type Pattern =
    "plain" | "batik" | "stripes" | "checks" | "tenun" | "rumbai";

